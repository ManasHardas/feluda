"""Typed request and response schemas for /api/v1. This file is the source of the API contract."""

from __future__ import annotations

from datetime import datetime, time
from typing import Annotated, Any
from uuid import UUID

from pydantic import AwareDatetime, BaseModel, ConfigDict, Field, StringConstraints, field_validator

from .enums import (
    AlertLevel,
    ApnsEnvironment,
    BackgroundMonitoring,
    BandEvidence,
    Classification,
    ConnectivityState,
    DeliveryStatus,
    DeviceStatus,
    EventResult,
    EventType,
    FailureMode,
    GapReason,
    HouseholdStatus,
    IncidentScope,
    IncidentStatus,
    InvitationStatus,
    Isp,
    MonitoringStatus,
    ObservationConfidence,
    Platform,
    PushProvider,
    StatusColor,
    Transport,
)


class Strict(BaseModel):
    """Requests reject unknown fields so clients cannot smuggle identifiers such as household_id."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)


class Out(BaseModel):
    model_config = ConfigDict(from_attributes=True)


InvitationToken = Annotated[str, StringConstraints(min_length=20, max_length=128, pattern=r"^[A-Za-z0-9_-]+$")]
HouseNumber = Annotated[str, StringConstraints(min_length=1, max_length=16)]
StreetName = Annotated[str, StringConstraints(min_length=1, max_length=80)]
DisplayLabel = Annotated[str, StringConstraints(min_length=1, max_length=40)]
VersionString = Annotated[str, StringConstraints(min_length=1, max_length=32, pattern=r"^[A-Za-z0-9._ ()+-]+$")]


class ErrorBody(Out):
    code: str
    message: str
    request_id: str | None = None


class ErrorResponse(Out):
    error: ErrorBody


