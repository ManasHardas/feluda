/// Everything a phone sends to join. The resident types only the street and, if they wish, the
/// house number. There is no account, e-mail address or password.
struct EnrollRequest: Codable, Sendable {
    let invitationToken: String
    let streetName: String
    /// Optional. Left out of the JSON when nil.
    let houseNumber: String?
    /// Always true: tapping "Join" under the privacy summary is the acknowledgement.
    let privacyAcknowledged: Bool
    /// Random UUID generated by the app at install time. Not a hardware identifier.
    let deviceID: UUID
    let platform: Platform
    let osVersion: String
    let appVersion: String
    let capabilities: DeviceCapabilities

    enum CodingKeys: String, CodingKey, CaseIterable {
        case invitationToken = "invitation_token"
        case streetName = "street_name"
        case houseNumber = "house_number"
        case privacyAcknowledged = "privacy_acknowledged"
        case deviceID = "device_id"
        case platform
        case osVersion = "os_version"
        case appVersion = "app_version"
        case capabilities
    }
}

struct EnrollResponse: Codable, Sendable {
